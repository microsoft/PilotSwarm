// Writes seed.json: the workflow_definition tool arguments (save, test, start) built from the example's files.
// Run it after changing support-desk.workflow.yaml, sample-input.json or fixtures.json:
//   node examples/workflows/support-desk/make-seed.mjs
import fs from "node:fs";

const here = new URL("./", import.meta.url);
const read = file => fs.readFileSync(new URL(file, here), "utf8");
const name = "support-desk";
const yaml = read("support-desk.workflow.yaml");
const inputs = JSON.parse(read("sample-input.json"));
const fixtures = JSON.parse(read("fixtures.json"));
const seed = {
    about: "workflow_definition tool arguments for the support-desk example, generated by make-seed.mjs from "
        + "support-desk.workflow.yaml, sample-input.json and fixtures.json (the SDK test workflow-example-support-desk checks "
        + "they match). save: create the session definition. test: a fully mocked test (no provider or model calls). "
        + "start: a live Workflow (needs a Cluster Decision Default and a chat model).",
    save: { operation: "save", name, yaml },
    test: { operation: "test", name, inputs, fixtures, expect: "done" },
    start: { operation: "start", name, inputs },
};
fs.writeFileSync(new URL("seed.json", here), `${JSON.stringify(seed, null, 2)}\n`);
