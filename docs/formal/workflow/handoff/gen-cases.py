#!/usr/bin/env python3
"""Writes cases.tsv, cases.json and tlc-templates.json for the FB-064 controller hand-off model, batch ch1.
No TLC is run here. The .cfg files are generated by run-tlc.sh (../../tlc_cases.py)."""
import json
import os as _os
import sys as _sys
_sys.path.insert(0, _os.path.join(_os.path.dirname(_os.path.abspath(__file__)), "..", ".."))
import tlc_cases   # docs/formal/tlc_cases.py

BATCH = "ch2"
M = "ControllerHandoff"


def q(x):
    return f'"{x}"'


def c(admitted=0, carry=False, approval=False, gate="admission", target="latest", n=3, cans=2, lenient=False):
    return dict(Admitted=admitted, CarryDecl=carry, ApprovalDecl=approval, GateBy=q(gate), Target=q(target), N=n,
                MaxCan=cans, LenientParse=lenient)


SAFE = ["TypeOK", "Inv_GateHolds", "Inv_NoCarryNull", "Inv_ApprovalGated", "Inv_NeverDown"]
LIVE = ["Prop_Ends"]

CASES = [
 ("ch.design-100", "design", c(), SAFE, LIVE, "PASS", "A 1.0.0 run with an ordinary plan moves to 1.1.0 at a continue-as-new."),
 ("ch.design-100-carry", "design", c(carry=True), SAFE, LIVE, "PASS",
  "A 1.0.0 run whose IR declares carry (only through the unsupported path): the admission gate keeps raw routing after the move."),
 ("ch.design-100-approval", "design", c(approval=True), SAFE, LIVE, "PASS",
  "A 1.0.0 run whose plan has an approval state fails at its first plan parse, before any continue-as-new."),
 ("ch.design-110-carry", "design", c(admitted=1, carry=True, approval=True), SAFE, LIVE, "PASS",
  "A 1.1.0 run with carry and an approval state: unchanged by FB-064."),
 ("ch.pinned-100-carry", "design", c(carry=True, target="pinned"), SAFE, LIVE, "PASS",
  "Before FB-064: the frozen handler pins 1.0.0 at continue-as-new."),
 ("mut.ch-gate-exec-carry", "mutant", c(carry=True, gate="execution"), ["Inv_GateHolds"], [], "VIOLATION:Inv_GateHolds",
  "Gating carry on the execution version: after the move a 1.0.0 run starts carry routing."),
 ("mut.ch-gate-exec-null", "mutant", c(carry=True, gate="execution"), ["Inv_NoCarryNull"], [], "VIOLATION:Inv_NoCarryNull",
  "The same: the first state after the move receives a carry envelope for a predecessor entered without a snapshot."),
 ("mut.ch-down", "mutant", c(admitted=1, target="down"), ["Inv_NeverDown"], [], "VIOLATION:Inv_NeverDown",
  "A continue-as-new to an older version."),
 ("wit.ch-moves", "witness", c(), ["W_NoMove"], [], "VIOLATION:W_NoMove", "A 1.0.0 run does move to 1.1.0."),
 # ---- ch2: the approval path is not vacuous ----
 ("wit.ch-approval-fails-at-parse", "witness", c(approval=True), ["W_NotFailed"], [], "VIOLATION:W_NotFailed",
  "ch.design-100-approval reaches its failure: the 1.0.0 parse refuses the approval state at the first execution."),
 ("ch.hyp-100-approval-crosses", "design", c(approval=True, lenient=True), SAFE, LIVE, "PASS",
  "Hypothetical: if the 1.0.0 parser accepted an approval state, the run could cross to 1.1.0; the admission-version "
  "gate in the activities still refuses the approval state, so it never activates."),
 ("wit.ch-approval-crosses", "witness", c(approval=True, lenient=True), ["W_NoApprovalCross"], [],
  "VIOLATION:W_NoApprovalCross", "In that hypothetical the crossing to a 1.1.0 execution is reachable."),
 ("mut.ch-approval-gate-exec", "mutant", c(approval=True, lenient=True, gate="execution"), ["Inv_ApprovalGated"], [],
  "VIOLATION:Inv_ApprovalGated", "Gating approval on the execution version: the crossed 1.0.0 run activates an approval state."),
]


def cfg(cid, consts, invs, props, note, expected):
    lines = [f"\\* {cid} ({BATCH}; expected {expected}): {note}", "SPECIFICATION Spec", "CONSTANTS"]
    lines += [f"    {k} = {str(v).upper() if isinstance(v, bool) else v}" for k, v in consts.items()]
    lines += ["INVARIANTS"] + [f"    {i}" for i in invs]
    if props:
        lines += ["PROPERTIES"] + [f"    {p}" for p in props]
    lines.append("CHECK_DEADLOCK TRUE")
    return "\n".join(lines) + "\n"


def main():
    rows, meta, texts = [], [], []
    for cid, group, consts, invs, props, expected, note in CASES:
        name = f"{cid}.cfg"
        texts.append(cfg(cid, consts, invs, props, note, expected))
        rows.append(f"{cid}\t{name}\t{M}")
        meta.append(dict(id=cid, module=M, group=group, spec="Spec", config=name, invariants=invs, properties=props,
                         expected=expected, deadlock=True, note=note, batch=BATCH, head="design"))
    assert len({r.split()[0] for r in rows}) == len(rows)
    tlc_cases.dump_json("tlc-templates.json", tlc_cases.attach(meta, texts), 2)
    with open("cases.tsv", "w") as f:
        f.write("\n".join(rows) + "\n")
    with open("cases.json", "w") as f:
        json.dump(meta, f, indent=1)
        f.write("\n")
    print(len(rows), "cases")


if __name__ == "__main__":
    main()
